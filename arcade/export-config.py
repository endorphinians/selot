"""Export the three arcade machines from the repository's Excel templates."""
import json
from pathlib import Path

import xlrd

ARCADE = Path(__file__).resolve().parent
SCRIPTS = ARCADE.parent / "resources" / "scripts"


def rows(filename, sheet_index=0):
    sheet = xlrd.open_workbook(SCRIPTS / f"{filename}.xls").sheet_by_index(sheet_index)
    columns = sheet.row_values(0)
    for index in range(1, sheet.nrows):
        yield {
            key: int(value) if isinstance(value, float) and value.is_integer() else value
            for key, value in zip(columns, sheet.row_values(index))
        }


def slot_rows(filename, slot, sheet_index=0):
    return [row for row in rows(filename, sheet_index) if row["slotsNum"] == slot]


def export_machine(slot, level):
    lobby = next(row for row in rows("slotsList") if row["type"] == slot and row["list"] == 1)
    columns = range(1, lobby["columns"] + 1)
    reels = sorted(
        (row for row in slot_rows("slots", slot, 1) if row["levelDown"] <= level <= row["levelUp"]),
        key=lambda row: row["turn"],
    )
    paylines = sorted(
        (row for row in rows("payLines") if row["lineType"] == lobby["lineType"]),
        key=lambda row: row["id"],
    )[:lobby["payLinesNum"]]
    symbols = {row["turn"] for row in slot_rows("slots", slot)}
    strips = [[row[f"reel{column}"] for row in reels] for column in columns]
    lines = [[row[f"position{column}"] - 1 for column in columns] for row in paylines]
    pays = sorted(slot_rows("slots", slot, 2), key=lambda row: -row["pay"])
    assert all(set(strip) <= symbols and len(strip) == lobby[f"reel{column}Num"]
               for column, strip in zip(columns, strips))
    assert len(lines) == lobby["payLinesNum"]
    assert all(0 <= row < lobby["rows"] for line in lines for row in line)
    return {
        "rows": lobby["rows"],
        "bets": [lobby[f"bet{index}"] * len(lines) for index in range(1, 6)],
        "reels": strips,
        "lines": lines,
        "pays": [[row["pay"], [row[f"combination{column}"] for column in columns]]
                 for row in pays],
    }


def write_config():
    machines = {key: export_machine(slot, level) for key, slot, level in
                [("aztec", 16, 18), ("ocean", 28, 500), ("sparta", 32, 12)]}
    for key, slot, symbol in [("aztec", 16, 2), ("sparta", 32, 5)]:
        scatter, = slot_rows("scatterGame", slot)
        machines[key]["scatter"] = [symbol, scatter["scatterNum"], scatter["freeSpinNum"]]
    puzzle, = slot_rows("bonusAztec", 16)
    machines["aztec"]["puzzle"] = [puzzle["puzzleNum"], puzzle["rewardNum"] // 100]
    ocean_bonus, = slot_rows("bonusOcean", 28)
    ocean_race, = slot_rows("bonusOcean", 28, 2)
    machines["ocean"]["ocean"] = {
        "bonusCount": ocean_bonus["bonusNum"],
        "bonuses": [[row["type"], row["rewardNum"], row["value"]]
                    for row in slot_rows("bonusOcean", 28, 1)],
        "raceCount": ocean_race["scatterNum"],
        "ranks": [[row["rank"], row["rewardNum"], row["value"]]
                  for row in slot_rows("bonusOcean", 28, 3)],
    }
    rewards = [row["itemNum"] for row in sorted(rows("signIn"), key=lambda row: row["day"])]
    lines = ["// Generated by export-config.py from resources/scripts.",
             "const slotTables = {"]
    for key, machine in machines.items():
        lines.append(f"  {key}: {{")
        for field, value in machine.items():
            if field in ("reels", "lines", "pays"):
                entries = ",\n".join(f"      {json.dumps(item)}" for item in value)
                lines.append(f"    {field}: [\n{entries}\n    ],")
            else:
                lines.append(f"    {field}: {json.dumps(value)},")
        lines.append("  },")
    lines.extend(["};", f"const dailyRewards = {json.dumps(rewards)};", ""])
    (ARCADE / "tables.js").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    write_config()
